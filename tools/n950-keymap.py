#!/usr/bin/env python3
"""The N950's keyboard matrix (the TWL4030 keypad's linux,keymap in
Linux's omap3-n950.dts) as set 1 scan codes, for kernel/platform/n950.c:

    n950-keymap.py omap3-n950.dts input-event-codes.h > kernel/platform/n950_keymap.h
"""
import re
import sys

dts, codes = open(sys.argv[1]).read(), open(sys.argv[2]).read()
key = {m[0]: int(m[1], 0) for m in re.findall(r'#define\s+(KEY_\w+)\s+(0x[0-9a-fA-F]+|\d+)', codes)}
block = dts[dts.index('&twl_keypad'):]
block = block[:block.index('};')]
# Linux key codes up to 88 are the XT (set 1) scan codes; the others that
# KolibriOS knows by their (extended) set 1 code
extra = {'KEY_UP': 0x48, 'KEY_DOWN': 0x50, 'KEY_LEFT': 0x4b, 'KEY_RIGHT': 0x4d,
         'KEY_RIGHTCTRL': 0x1d, 'KEY_RIGHTALT': 0x38, 'KEY_LEFTMETA': 0x5b,
         'KEY_COMPOSE': 0x5d, 'KEY_DELETE': 0x53, 'KEY_HOME': 0x47, 'KEY_END': 0x4f,
         'KEY_PAGEUP': 0x49, 'KEY_PAGEDOWN': 0x51, 'KEY_INSERT': 0x52}
table = [[0] * 8 for _ in range(8)]
names = [[''] * 8 for _ in range(8)]
for row, col, name in re.findall(r'MATRIX_KEY\(\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*(KEY_\w+)\s*\)', block):
    r, c = int(row, 0), int(col, 0)
    code = key.get(name, 0)
    sc = extra.get(name, code if 0 < code <= 88 else 0)
    table[r][c] = sc
    names[r][c] = name
print('/* generated by tools/n950-keymap.py from omap3-n950.dts: the TWL4030 keypad')
print(' * matrix [row][column] as set 1 scan codes (0: not a key KolibriOS has) */')
print('static const unsigned char n950_keymap[8][8] = {')
for r in range(8):
    cells = ', '.join('0x%02x' % v for v in table[r])
    print('\t{ %s }, /* %s */' % (cells, ' '.join(n[4:] if n else '-' for n in names[r])))
print('};')
