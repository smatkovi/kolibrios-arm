#!/usr/bin/env python3
"""The Pro1X's Wi-Fi regulatory tables: kernel/modem/regdb.c.

Two sources, as Linux uses them for the WCN3990 (ath10k):

 - ath's own tables (drivers/net/wireless/ath/regd.h, regd_common.h of a
   Linux tree, ISC licence): the country codes (enum CountryCode), the
   regulatory domain values (enum EnumRd), regDomainPairs (a domain's
   conformance test limits, 5 and 2 GHz) and allCountries (ath's country
   code, its domain, the ISO name);
 - wireless-regdb's regulatory.db (ISC licence), the binary file Linux's
   cfg80211 loads (net/wireless/reg.c: struct fwdb_header, fwdb_country,
   fwdb_collection, fwdb_rule): each country's DFS region and its rules
   (the range in kHz, the largest bandwidth, the EIRP in mBm, the flags
   NO-OFDM, NO-OUTDOOR, DFS, NO-IR, AUTO-BW). Only the rules of 2-6 GHz.

Usage: gen-regdb.py LINUX_TREE REGULATORY_DB OUT.c
"""
import hashlib
import re
import struct
import sys


def c_enum(text, name):
    m = re.search(r"enum\s+" + name + r"\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit("no enum " + name)
    out = {}
    for ident, val in re.findall(r"(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)", m.group(1)):
        out[ident] = int(val, 0)
    return out


def c_array(text, name):
    m = re.search(name + r"\[\]\s*=\s*\{(.*?)\n\};", text, re.S)
    if not m:
        sys.exit("no array " + name)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [tuple(x.strip() for x in e.split(",")) for e in re.findall(r"\{([^{}]*)\}", body)]


def main():
    linux, dbfile, out = sys.argv[1:4]
    regd_h = open(linux + "/drivers/net/wireless/ath/regd.h").read()
    common = open(linux + "/drivers/net/wireless/ath/regd_common.h").read()
    countries = c_enum(regd_h, "CountryCode")
    ctl = c_enum(regd_h, "ctl_group")
    ctl["NO_CTL"] = int(re.search(r"#define\s+NO_CTL\s+(0x\w+)", regd_h).group(1), 16)
    ctl["SD_NO_CTL"] = int(re.search(r"#define\s+SD_NO_CTL\s+(0x\w+)", regd_h).group(1), 16)
    for name in ("CTRY_DEBUG", "CTRY_DEFAULT"):
        countries[name] = int(re.search(r"#define\s+" + name + r"\s+(0x\w+|\d+)", regd_h).group(1), 0)
    rd = c_enum(common, "EnumRd")

    def val(s):
        for t in (rd, ctl, countries):
            if s in t:
                return t[s]
        return int(s, 0)

    pairs = [(val(a), val(b), val(c)) for a, b, c in c_array(common, "regDomainPairs")]
    allc = [(val(a), val(b), c.strip('"')) for a, b, c in c_array(common, "allCountries")]

    db = open(dbfile, "rb").read()
    magic, version = struct.unpack_from(">II", db, 0)
    if magic != 0x52474442 or version != 20:
        sys.exit("not a regulatory.db (FWDB_MAGIC, FWDB_VERSION 20)")
    regdb = []
    off = 8
    while True:
        alpha2, coll_ptr = struct.unpack_from(">2sH", db, off)
        off += 4
        if not coll_ptr:
            break
        c = coll_ptr << 2
        clen, n_rules, dfs = struct.unpack_from(">BBB", db, c)
        rules = []
        for i in range(n_rules):
            rp = struct.unpack_from(">H", db, c + ((clen + 1) & ~1) + 2 * i)[0] << 2
            rlen, flags, eirp, start, end, maxbw = struct.unpack_from(">BBHIII", db, rp)
            if end > 2000000 and start < 6000000:
                rules.append((start, end, maxbw, eirp, flags))
        if len(rules) > 8:
            sys.exit("more than 8 rules of 2-6 GHz in " + alpha2.decode() + " (regd.c's DOM_RULES)")
        regdb.append((alpha2.decode(), dfs, rules))

    o = []
    o.append("/* KolibriOS for ARM: the Wi-Fi's regulatory tables, generated by")
    o.append(" * tools/gen-regdb.py (docs/pro1x-network.md, the regulatory domain):")
    o.append(" *  - ath's: Linux's drivers/net/wireless/ath/regd.h, regd_common.h")
    o.append(" *    (Copyright (c) 2008-2009 Atheros Communications Inc., ISC licence):")
    o.append(" *    regDomainPairs, allCountries;")
    o.append(" *  - wireless-regdb's regulatory.db (sha256 %s;" % hashlib.sha256(db).hexdigest()[:16])
    o.append(" *    Copyright (c) 2008 Luis R. Rodriguez, Johannes Berg, Michael Green,")
    o.append(" *    ISC licence): each country's DFS region and rules of 2-6 GHz.")
    o.append(" * Do not edit; run the tool again. */")
    o.append('#include "regd.h"')
    o.append("")
    o.append("const struct ath_regpair ath_regpairs[] = {")
    for a, b, c in pairs:
        o.append("\t{ 0x%02x, 0x%02x, 0x%02x }," % (a, b, c))
    o.append("};")
    o.append("const u32 ath_nregpairs = %d;" % len(pairs))
    o.append("")
    o.append("const struct ath_country ath_countries[] = {")
    for a, b, c in allc:
        o.append('\t{ %d, 0x%02x, "%s" },' % (a, b, c))
    o.append("};")
    o.append("const u32 ath_ncountries = %d;" % len(allc))
    o.append("")
    o.append("const struct regdb_rule regdb_rules[] = {")
    first = []
    n = 0
    for alpha2, dfs, rules in regdb:
        first.append(n)
        for start, end, maxbw, eirp, flags in rules:
            o.append("\t{ %d, %d, %d, %d, 0x%02x }, /* %s */" % (start, end, maxbw, eirp, flags, alpha2))
            n += 1
    o.append("};")
    o.append("")
    o.append("const struct regdb_country regdb_countries[] = {")
    for (alpha2, dfs, rules), f in zip(regdb, first):
        o.append('\t{ "%s", %d, %d, %d },' % (alpha2, dfs, len(rules), f))
    o.append("};")
    o.append("const u32 regdb_ncountries = %d;" % len(regdb))
    open(out, "w").write("\n".join(o) + "\n")
    print("%s: %d regpairs, %d ath countries, %d regdb countries, %d rules" % (out, len(pairs), len(allc), len(regdb), n))


main()
