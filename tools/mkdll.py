#!/usr/bin/env python3
"""KolibriOS for ARM's libraries (docs/threads.md): the export table of a
library and the import table and stubs of a program that uses it, both
from the library's list of exports (lib/NAME/NAME.exp), and a check of
the linked library.

    mkdll.py exports LIST OUT.S         the library's EXPORTS table
    mkdll.py imports LIST FILE OUT.S    a program's @IMPORT entry for /sys/lib/FILE,
                                        its import table and a stub per function
    mkdll.py check LIB.obj              only relocations the kernel applies (68.19)

LIST: a line per export, in KolibriOS's order, "#" comments:
    NAME            a function: its C name is NAME
    NAME SYMBOL     a function exported as NAME, SYMBOL in C
    NAME =VALUE     a value (a version: "version =0x00020009")
    NAME SYMBOL lib a function only the library has (no stub: lib_init)

The export table is KolibriOS's: { name, value } pairs of words, then
0, 0. The import side is dll.inc's: the program's .kos_import section
holds { table, file name } pairs (lib/app.ld ends them with 0, 0; the C
library's start calls dll_load on them, lib/libc/dll.c), the table one
word per function, a pointer to its name until dll.Link puts the
function's address there; each stub jumps through its word.
"""
import struct
import sys


def read_list(path):
    out = []
    for line in open(path):
        line = line.split('#', 1)[0].split()
        if not line:
            continue
        name = line[0]
        if len(line) > 1 and line[1].startswith('='):
            out.append((name, None, line[1][1:], False))
        else:
            sym = line[1] if len(line) > 1 else name
            out.append((name, sym, None, len(line) > 2 and line[2] == 'lib'))
    return out


def label(i):
    return f'.Ln{i}'


def exports(lst, out):
    s = ['/* generated by tools/mkdll.py from ' + sys.argv[2] + ': the export table */',
         '\t.syntax unified', '\t.section .data.rel.ro.EXPORTS, "aw"', '\t.balign 4',
         '\t.global EXPORTS', '\t.type EXPORTS, %object', 'EXPORTS:']
    for i, (name, sym, val, _) in enumerate(lst):
        s.append(f'\t.word {label(i)}, {val if val is not None else sym}')
    s += ['\t.word 0, 0', '\t.size EXPORTS, . - EXPORTS', '\t.section .rodata.EXPORTS.names, "a"']
    for i, (name, *_ ) in enumerate(lst):
        s.append(f'{label(i)}:\t.asciz "{name}"')
    open(out, 'w').write('\n'.join(s) + '\n')


def imports(lst, fname, out):
    base = fname.split('.')[0].replace('-', '_')
    tab = f'__imp_{base}'
    funcs, seen = [], set()
    for n, sym, val, libonly in lst:       # a function under two names: the first
        if val is None and not libonly and sym not in seen:
            funcs.append((n, sym))
            seen.add(sym)
    s = ['/* generated by tools/mkdll.py from ' + sys.argv[2] + ': the imports of ' + fname + ' */',
         '\t.syntax unified', '\t.arm',
         '\t.section .kos_import, "a"', f'\t.word {tab}, .Llib',
         '\t.section .rodata.imp_names, "a"', f'.Llib:\t.asciz "{fname}"']
    for i, (n, _) in enumerate(funcs):
        s.append(f'{label(i)}:\t.asciz "{n}"')
    s += ['\t.data', '\t.balign 4', f'\t.global {tab}', f'{tab}:']
    for i, (n, sym) in enumerate(funcs):
        s.append(f'.Lslot{i}:\t.word {label(i)}')
    s += ['\t.word 0', '\t.text', '\t.balign 4']
    for i, (n, sym) in enumerate(funcs):
        s += [f'\t.global {sym}', f'\t.type {sym}, %function', f'{sym}:',
              f'\tldr\tip, .Lp{i}', '\tldr\tpc, [ip]', f'.Lp{i}:\t.word .Lslot{i}',
              f'\t.size {sym}, . - {sym}']
    open(out, 'w').write('\n'.join(s) + '\n')


# the relocations kernel/dll.c applies
OK_RELOCS = {0: 'NONE', 2: 'ABS32', 21: 'GLOB_DAT', 22: 'JUMP_SLOT', 23: 'RELATIVE'}


def check(path):
    d = open(path, 'rb').read()
    if d[:7] != b'\x7fELF\x01\x01\x01':
        sys.exit(f'{path}: not an ELF32 little endian file')
    etype, machine = struct.unpack_from('<HH', d, 16)
    if etype != 3 or machine != 40:
        sys.exit(f'{path}: not an ARM shared object (type {etype}, machine {machine})')
    shoff, = struct.unpack_from('<I', d, 32)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', d, 46)
    secs = [struct.unpack_from('<IIIIIIIIII', d, shoff + i * shentsize) for i in range(shnum)]
    names = secs[shstrndx]
    bad, exports, needed = [], False, False
    for sh in secs:
        name = d[names[4] + sh[0]:d.index(b'\0', names[4] + sh[0])].decode()
        if sh[1] == 4:
            bad.append(f'{name}: RELA')
        if sh[1] == 9:
            for o in range(sh[4], sh[4] + sh[5], 8):
                t = struct.unpack_from('<I', d, o + 4)[0] & 0xff
                if t not in OK_RELOCS:
                    bad.append(f'{name}: relocation type {t} at {struct.unpack_from("<I", d, o)[0]:#x}')
        if sh[1] == 11:                  # .dynsym
            strtab = secs[sh[6]]
            for o in range(sh[4] + 16, sh[4] + sh[5], 16):
                n, = struct.unpack_from('<I', d, o)
                if d[strtab[4] + n:strtab[4] + n + 8] == b'EXPORTS\0':
                    exports = True
        if sh[1] == 6:                   # .dynamic
            for o in range(sh[4], sh[4] + sh[5], 8):
                tag, = struct.unpack_from('<i', d, o)
                if tag == 1:
                    needed = True
                if tag == 0:
                    break
    if needed:
        bad.append('it needs other libraries (DT_NEEDED)')
    if not exports:
        bad.append('no EXPORTS in its dynamic symbols')
    if bad:
        sys.exit(f'{path}: ' + '; '.join(bad[:10]))


if __name__ == '__main__':
    if sys.argv[1] == 'exports':
        exports(read_list(sys.argv[2]), sys.argv[3])
    elif sys.argv[1] == 'imports':
        imports(read_list(sys.argv[2]), sys.argv[3], sys.argv[4])
    elif sys.argv[1] == 'check':
        check(sys.argv[2])
    else:
        sys.exit(__doc__)
