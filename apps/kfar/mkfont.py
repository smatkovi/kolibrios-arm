#!/usr/bin/env python3
"""kfar's font for KolibriOS for ARM: font.inc of kfar (programs/fs/kfar,
by diamond and the KolibriOS team, GPL-2.0) as a script: the glyphs of a
monochrome BMP of 16 x 16 characters into C.

    mkfont.py FONT.bmp OUTDIR [--show CHAR]

writes OUTDIR/font.h (font_width, font_height, extern font[]) and
OUTDIR/font_data.h (the table). The table is font.inc's: for each scan
line of the characters, 256 entries (one per character), a byte each
(a 16-bit word for fonts wider than 8), bit 0 the leftmost pixel, a set
bit the character's colour. --show prints one glyph to stderr. """
import struct
import sys


def main():
    args = sys.argv[1:]
    show = None
    if '--show' in args:
        i = args.index('--show')
        show = args[i + 1]
        del args[i:i + 2]
    bmp, outdir = args
    data = open(bmp, 'rb').read()
    # font.inc's sanity checks
    if data[0:2] != b'BM' or struct.unpack_from('<I', data, 0xE)[0] != 0x28:
        sys.exit(f'{bmp}: not BMP file!')
    w, h = struct.unpack_from('<II', data, 0x12)
    if (w & 0xF) or (h & 0xF) or w > 16 * 16:
        sys.exit(f'{bmp}: font: invalid width or height')
    if struct.unpack_from('<I', data, 0x1A)[0] != 0x10001:
        sys.exit(f'{bmp}: font: not monochrome bitmap')
    fw, fh = w >> 4, h >> 4
    scanline = (fw * 2 + 3) & ~3
    mask = (1 << fw) - 1

    def rev8(b):
        return int(f'{b:08b}'[::-1], 2)

    table = []
    for cur_scan in range(1, fh + 1):
        for row in range(1, 17):
            off = 0x3E + scanline * (fh * (17 - row) - cur_scan)
            line = bytes(rev8(b) for b in data[off:off + fw * 2]) + b'\0\0\0\0'
            for col in range(16):
                bit = col * fw
                a1 = struct.unpack_from('<I', line, bit >> 3)[0]
                a1 = (a1 >> (bit & 7)) & mask
                table.append(a1 ^ mask)

    if show is not None:
        c = ord(show) if len(show) == 1 else int(show, 0)
        for s in range(fh):
            v = table[s * 256 + c]
            print(''.join('#' if v >> x & 1 else '.' for x in range(fw)), file=sys.stderr)

    ctype = 'unsigned short' if fw > 8 else 'unsigned char'
    with open(f'{outdir}/font.h', 'w') as f:
        f.write(f'/* generated by apps/kfar/mkfont.py from {bmp.split("/")[-1]} */\n'
                '#ifndef KFAR_FONT_H\n#define KFAR_FONT_H\n'
                f'#define font_width {fw}\n#define font_height {fh}\n'
                f'typedef {ctype} font_t;\n'
                'extern const font_t font[256 * font_height];\n#endif\n')
    with open(f'{outdir}/font_data.h', 'w') as f:
        f.write(f'/* generated by apps/kfar/mkfont.py from {bmp.split("/")[-1]} */\n'
                'const font_t font[256 * font_height] = {\n')
        for i in range(0, len(table), 16):
            f.write('\t' + ', '.join(f'0x{v:02x}' for v in table[i:i + 16]) + ',\n')
        f.write('};\n')


main()
